"""確保 Docker 基底映像、依賴鎖檔與測試使用同一個 Python 版本。

CI 從 Dockerfile 讀取 Python 版本來跑測試；Dependabot 更新基底映像的 minor
版本時，若鎖檔沒有用 scripts/lock_dependencies.ps1 重產，這裡會失敗提醒。
"""
from pathlib import Path
import os
import re
import sys
import unittest

ROOT = Path(__file__).resolve().parents[1]
BASE_RE = re.compile(r"^FROM python:(\d+)\.(\d+)(?:\.\d+)?-\S+ AS base\r?$", re.M)
LOCK_RE = re.compile(r"autogenerated by pip-compile with Python (\d+)\.(\d+)")


def dockerfile_python():
    match = BASE_RE.search((ROOT / "Dockerfile").read_text(encoding="utf-8"))
    if not match:
        raise AssertionError("Dockerfile 找不到 python base 映像版本")
    return int(match[1]), int(match[2])


class PythonVersionTest(unittest.TestCase):
    def test_locks_match_dockerfile(self):
        expected = dockerfile_python()
        locks = sorted((ROOT / "requirements-locks").glob("*.txt"))
        self.assertTrue(locks)
        for lock in locks:
            match = LOCK_RE.search(lock.read_text(encoding="utf-8"))
            self.assertIsNotNone(match, lock.name)
            self.assertEqual((int(match[1]), int(match[2])), expected,
                             f"{lock.name} 與 Dockerfile 的 Python 版本不同，請執行 scripts/lock_dependencies.ps1")

    def test_ci_python_matches_dockerfile(self):
        # 只在 CI 檢查：本機 Windows .venv 可以用其他版本。
        if os.environ.get("GITHUB_ACTIONS") != "true":
            self.skipTest("僅在 GitHub Actions 檢查")
        self.assertEqual(sys.version_info[:2], dockerfile_python())


if __name__ == "__main__":
    unittest.main()
